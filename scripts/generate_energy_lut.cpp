// Deterministic directional-albedo tables for Xenon's height-correlated GGX.
// Build: c++ -O3 -std=c++20 -mavx2 -mfma -fopenmp -Isrc scripts/generate_energy_lut.cpp -o
// /tmp/xenon-energy-lut Run: /tmp/xenon-energy-lut > src/material/energy_lut_data.inc
#include "material/bsdf.h"
#include <cstdio>
#include <vector>
using namespace xn;

static float radical_inverse(unsigned n) {
	n = (n << 16) | (n >> 16);
	n = ((n & 0x55555555u) << 1) | ((n & 0xaaaaaaaau) >> 1);
	n = ((n & 0x33333333u) << 2) | ((n & 0xccccccccu) >> 2);
	n = ((n & 0x0f0f0f0fu) << 4) | ((n & 0xf0f0f0f0u) >> 4);
	n = ((n & 0x00ff00ffu) << 8) | ((n & 0xff00ff00u) >> 8);

	return n * 2.3283064365386963e-10f;
}

int main() {
	constexpr int NR = 33, NM = 65, NI = 33, NS = 8192;
	// Channel zero is F=1 energy; channels 1..NI integrate exact dielectric Fresnel.
	std::vector<float> data(NR * NM * (NI + 1));
#pragma omp parallel for schedule(dynamic)
	for (int ir = 0; ir < NR; ++ir) {
		float rough = float(ir) / (NR - 1), alpha = std::max(rough * rough, 1e-6f);

		for (int im = 0; im < NM; ++im) {
			float mu = std::max(float(im) / (NM - 1), 1e-5f);
			Vec3 wo(std::sqrt(1 - mu * mu), 0, mu);
			double sums[NI + 1] = {};

			for (int sample = 0; sample < NS; ++sample) {
				Vec3 wh =
					sample_vndf_ggx(wo, alpha, alpha, (sample + .5f) / NS, radical_inverse(sample));
				Vec3 wi = reflect(-wo, wh);

				if (wi.z <= 0)
					continue;
				float weight = ggx_g2(wo, wi, alpha) / ggx_g1(wo, alpha);
				sums[0] += weight;

				for (int ii = 0; ii < NI; ++ii) {
					float a = float(ii) / (NI - 1), ior = 1.f + 2.f * a * a;
					sums[ii + 1] += weight * fresnel_dielectric(dot(wo, wh), ior);
				}
			}

			for (int ii = 0; ii <= NI; ++ii)
				data[(ii * NR + ir) * NM + im] = float(sums[ii] / NS);
		}
	}
	// Analytic integral of the piecewise-linear cosine interpolant.
	auto average = [&](int channel, int rough) {
		double sum = 0, step = 1.0 / (NM - 1);

		for (int i = 0; i < NM - 1; ++i) {
			float a = data[(channel * NR + rough) * NM + i],
				  b = data[(channel * NR + rough) * NM + i + 1];
			sum += 2 * step * ((i * step) * (a + b) * .5 + step * (a + 2 * b) / 6);
		}

		return float(sum);
	};

	for (int ir = 0; ir < NR; ++ir)
		data.push_back(average(0, ir));

	for (int ii = 0; ii < NI; ++ii)
		data.push_back(average(ii + 1, 0));

	for (int ii = 0; ii < NI; ++ii)
		for (int ir = 0; ir < NR; ++ir)
			data.push_back(average(ii + 1, ir));
	std::puts(
		"// Generated by scripts/generate_energy_lut.cpp; 8192 deterministic VNDF samples/cell.");

	for (size_t i = 0; i < data.size(); ++i) {
		std::printf("%.9ef,%s", data[i], (i + 1) % 8 == 0 ? "\n" : " ");
	}
	std::puts("");
}
